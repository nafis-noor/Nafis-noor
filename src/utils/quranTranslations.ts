export function getQuranTranslations(langInput?: string): QuranTranslations {
  const code = getLanguageCode(langInput || getGlobalLanguage());
  return QURAN_TRANSLATIONS[code] || QURAN_TRANSLATIONS.en;
}

export function getQuranEdition(langInput?: string): QuranEditionInfo {
  const code = getLanguageCode(langInput || getGlobalLanguage());
  return QURAN_EDITIONS[code] || QURAN_EDITIONS.en;
}

export function useQuranLanguage(propLang?: string): {
  activeLang: SupportedLanguageCode;
  qt: QuranTranslations;
  edition: QuranEditionInfo;
} {
  const [currentLang, setCurrentLang] = useState<SupportedLanguageCode>(() => {
    return getLanguageCode(propLang || getGlobalLanguage());
  });

  useEffect(() => {
    if (propLang) {
      setCurrentLang(getLanguageCode(propLang));
    }
  }, [propLang]);

  useEffect(() => {
    const handleLangChange = (e: Event) => {
      const customEvent = e as CustomEvent<{ language: string }>;
      if (customEvent.detail && customEvent.detail.language) {
        setCurrentLang(getLanguageCode(customEvent.detail.language));
      }
    };

    window.addEventListener('app_language_changed', handleLangChange);
    return () => {
      window.removeEventListener('app_language_changed', handleLangChange);
    };
  }, []);

  const activeLang = getLanguageCode(propLang || currentLang);
  const qt = getQuranTranslations(activeLang);
  const edition = getQuranEdition(activeLang);

  return { activeLang, qt, edition };
}
